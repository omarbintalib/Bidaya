const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.argv[2] || 'http://127.0.0.1:5184';
const progressKey = 'bidaya.journey.v1';
const chatKey = 'bidaya.chats.v1';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    for (const [width, locale, motion, textSize, contrast] of [[1440, 'en', 'no-preference', 100, 'brand'], [390, 'ar', 'reduce', 150, 'dark'], [320, 'en', 'reduce', 150, 'light'], [390, 'en', 'no-preference', 100, 'brand']]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: motion });
      await context.addInitScript(({ locale, textSize, contrast }) => {
        if (localStorage.getItem('qa-seeded')) return;
        localStorage.setItem('qa-seeded', '1'); sessionStorage.setItem('bidaya.intro.seen', '1');
        localStorage.setItem('bidaya.locale', locale);
        localStorage.setItem('islamathon.accessibility.v1', JSON.stringify({ textSize, contrast }));
        localStorage.setItem('bidaya.journey.v1', JSON.stringify({ answers: { oldQuiz: 'makkah' }, seen: [12, 59], lastEvent: 59 }));
        localStorage.setItem('bidaya.chats.v1', JSON.stringify([{ id: 2, question: 'Legacy second', answer: 'Medina', locale: 'en' }, { id: 1, question: 'Legacy first', answer: 'Makkah', locale: 'en' }]));
      }, { locale, textSize, contrast });
      const page = await context.newPage(); const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(`${base}/journey`);
      await page.waitForSelector('.logo-transition', { state: 'detached' });
      await page.waitForSelector('.resume-dialog[open]');
      assert.match(await page.locator('.resume-dialog').innerText(), locale === 'ar' ? /تبقى محادثاتك/ : /chats stay saved/);
      await page.locator('.resume-dialog .btn-primary').click();
      await page.waitForFunction(() => document.querySelector('.step-event.is-on .ecard-title')?.textContent?.includes('Badr') || document.querySelector('.step-event.is-on .ecard-title')?.textContent?.includes('بدر'));
      const reading = () => page.evaluate(() => ({ step: document.querySelector('.step.is-on')?.getAttribute('data-step'), offset: document.querySelector('.step.is-on')?.getBoundingClientRect().top - document.querySelector('.story-toolbar')?.getBoundingClientRect().bottom }));
      await page.waitForTimeout(300);
      const before = await reading();
      await page.locator('.language-switch').evaluate(button => button.click());
      await page.waitForFunction(() => !document.documentElement.dataset.readingRestore);
      const after = await reading();
      assert.equal(after.step, before.step); assert.ok(Math.abs(after.offset - before.offset) < 3, `Reading moved ${after.offset - before.offset}px`);
      const currentLocale = locale === 'en' ? 'ar' : 'en';
      const wide = width > 1000;
      if (!wide) await page.locator('.tb-ask').click();
      const icon = page.locator(wide ? '.ask-bar-history' : '.ask-panel .mo-history');
      await icon.waitFor({ state: 'visible' });
      await icon.focus();
      await page.waitForFunction(selector => document.activeElement === document.querySelector(selector), wide ? '.ask-bar-history' : '.ask-panel .mo-history');
      assert.equal(await icon.evaluate(el => getComputedStyle(el, '::after').opacity), '1');
      await icon.click();
      assert.equal(await page.locator('.chat-history-list time').count(), 0);
      assert.equal(await page.locator('.chat-history-list .answer-references a').count(), 0);
      await page.locator('.chat-search input').fill('Makkah');
      assert.equal(await page.locator('.chat-history-list li').count(), 1);
      await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('Denied')) } }));
      await page.locator('.chat-controls button').first().click();
      assert.match(await page.locator('.chat-notice').innerText(), currentLocale === 'ar' ? /تحديد/ : /Select/);
      await page.locator('.chat-controls button').last().click();
      assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, chatKey), 1);
      await page.keyboard.press('Escape');
      const input = page.locator(wide ? '.ask-bar input' : '.ask-panel .mo-field');
      await input.fill('When was the Battle of Badr?'); await input.press('Enter');
      const responseSelector = wide ? '.answer-card .mo-root' : '.ask-panel .mo-root';
      await page.waitForFunction(selector => document.querySelector(selector)?.dataset.phase === 'answered', responseSelector, { timeout: 15000 });
      const panel = page.locator(wide ? '.answer-card' : '.ask-panel');
      const expand = panel.locator('.mo-reading-actions > button');
      if (await expand.count()) {
        const collapsed = await page.locator(responseSelector).evaluate(el => parseFloat(el.style.getPropertyValue('--answer-height')));
        await expand.click(); assert.equal(await expand.getAttribute('aria-expanded'), 'true');
        assert.ok((await page.locator(responseSelector).evaluate(el => parseFloat(el.style.getPropertyValue('--answer-height')))) > collapsed);
      } else assert.equal(await page.locator(responseSelector).getAttribute('data-answer-overflow'), 'false');
      assert.equal(await panel.locator('.answer-references a').count(), 1);
      assert.equal(await panel.locator('.answer-references button').count(), 1);
      await page.screenshot({ path: `qa/journey-expanded-${width}-${locale}.png` });
      await panel.locator('.answer-references button').click();
      const records = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), chatKey);
      assert.equal(records.length, 2); assert.ok(records[0].createdAt); assert.equal(records[0].event, 59); assert.match(records[0].sources[0].url, /^https:\/\//);
      await page.reload(); await page.waitForSelector('.logo-transition', { state: 'detached' });
      await page.waitForSelector('.resume-dialog[open]');
      await page.screenshot({ path: `qa/journey-resume-${width}-${locale}.png` });
      await page.locator('.resume-dialog .btn-quiet:last-child').click();
      await page.waitForSelector('.resume-dialog', { state: 'detached' });
      const reset = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), progressKey);
      assert.deepEqual(reset.answers, {}); assert.deepEqual(reset.seen, []); assert.equal(reset.lastEvent, undefined);
      assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, chatKey), 2);
      await page.goto(`${base}/missing`); await page.waitForSelector('.logo-transition', { state: 'detached' });
      const skip = page.locator('.skip-content'); await skip.focus(); assert.ok((await skip.boundingBox()).y >= 0);
      const url = page.url(); await page.keyboard.press('Enter'); assert.equal(page.url(), url); assert.equal(await page.evaluate(() => document.activeElement.tagName), 'MAIN');
      assert.equal(await page.locator('.not-found-page .recovery-panel').count(), 0);
      assert.ok((await page.locator('.not-found-number').boundingBox()).height >= 180);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.screenshot({ path: `qa/not-found-${width}-${locale}.png` });
      assert.deepEqual(errors, []);
      console.log(`Continuity, reset, language position, history controls, sources, expansion, tooltip focus, skip, 404: ${width}px ${locale} ${motion} ${textSize}% ${contrast}`);
      await context.close();
    }
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
